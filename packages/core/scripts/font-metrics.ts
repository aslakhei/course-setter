// Generates src/text/metrics.data.ts from the font files in packages/core/fonts: the vertical metrics
// and advance widths core needs to measure text and break it into lines. Run after adding or changing
// a font (a test checks the file matches the fonts):
//
//   node packages/core/scripts/font-metrics.ts
import { readFileSync, writeFileSync } from 'node:fs'
import fontkit from '@pdf-lib/fontkit'
import { FONT_IDS, FONTS } from '../src/text/fonts.ts'
import { CHARACTER_RUNS, type FontMetrics } from '../src/text/metrics.ts'

const FONT_DIR = new URL('../fonts/', import.meta.url)
const OUT = new URL('../src/text/metrics.data.ts', import.meta.url)

/** A font's metrics, in its own units: advance widths of the characters in CHARACTER_RUNS (null where it has no glyph). */
export function fontMetrics(file: string): FontMetrics {
  const font = fontkit.create(readFileSync(new URL(file, FONT_DIR)))
  return {
    unitsPerEm: font.unitsPerEm,
    ascent: font.ascent,
    descent: font.descent,
    capHeight: font.capHeight,
    missing: font.getGlyph(0).advanceWidth,
    widths: CHARACTER_RUNS.map(([from, to]) => {
      const run: (number | null)[] = []
      for (let c = from; c <= to; c++) run.push(font.hasGlyphForCodePoint(c) ? font.glyphForCodePoint(c).advanceWidth : null)
      return run
    }),
  }
}

/** The contents of metrics.data.ts. */
export function metricsSource(): string {
  const entries = FONT_IDS.map(id => `  '${id}': ${JSON.stringify(fontMetrics(FONTS[id].file))},`)
  return [
    '// Generated by scripts/font-metrics.ts from the files in packages/core/fonts. Do not edit.',
    "import type { FontId } from './fonts.ts'",
    "import type { FontMetrics } from './metrics.ts'",
    '',
    'export const METRICS: Record<FontId, FontMetrics> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
}

if (import.meta.main) {
  writeFileSync(OUT, metricsSource())
  console.log(`wrote ${OUT.pathname}`)
}
