// Generates src/descriptions/symbols.data.ts from Purple Pen's symbol database (symbols.xml), which has
// vector drawings of every IOF control description symbol. Purple Pen is BSD 3-clause licensed, see
// THIRD-PARTY-NOTICES.md. Run by hand when updating to a newer Purple Pen commit:
//
//   node packages/core/scripts/import-description-symbols.ts [path/to/symbols.xml]
//
// Without a path, the file is downloaded from the pinned commit below.
import { readFileSync, writeFileSync } from 'node:fs'

const COMMIT = 'af2b6c41ef1d8ad718ddd4fa3c7a15a1db508014'
const SOURCE_URL = `https://raw.githubusercontent.com/petergolde/PurplePen/${COMMIT}/src/PurplePenCore/symbols.xml`
const OUT = new URL('../src/descriptions/symbols.data.ts', import.meta.url)

type Command = ['M', number, number] | ['L', number, number] | ['C', number, number, number, number, number, number] | ['Z']
type Shape =
  | { disc: [number, number, number] }
  | { circle: [number, number, number]; width: number }
  | { line: Command[]; width: number; cap: 'butt' | 'round'; join: 'miter' | 'round' }
  | { area: Command[] }

const attr = (tag: string, name: string): string | undefined => tag.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1]
const num = (tag: string, name: string): number => {
  const v = attr(tag, name)
  if (v === undefined) throw new Error(`missing ${name} in ${tag}`)
  return Number(v)
}
const points = (body: string): [number, number][] =>
  [...body.matchAll(/<point\b[^>]*>/g)].map(m => [num(m[0], 'x'), num(m[0], 'y')] as [number, number])
const polyline = (pts: [number, number][], closed: boolean): Command[] => [
  ...pts.map(([x, y], i): Command => [i === 0 ? 'M' : 'L', x, y]),
  ...(closed ? [['Z'] as Command] : []),
]
const beziers = (pts: [number, number][], closed: boolean): Command[] => {
  const [first, ...rest] = pts
  if (!first || rest.length % 3 !== 0) throw new Error('beziers need 1 + 3n points')
  const out: Command[] = [['M', ...first]]
  for (let i = 0; i < rest.length; i += 3) {
    const [a, b, c] = [rest[i], rest[i + 1], rest[i + 2]] as [[number, number], [number, number], [number, number]]
    out.push(['C', a[0], a[1], b[0], b[1], c[0], c[1]])
  }
  if (closed) out.push(['Z'])
  return out
}
// Purple Pen's defaults (SymbolDB.cs): round ends and corners unless stated; "flat" ends, "sharp" corners.
const cap = (tag: string) => (attr(tag, 'ends') === 'flat' ? 'butt' : 'round')
const join = (tag: string) => (attr(tag, 'corners') === 'sharp' ? 'miter' : 'round')

function shape(element: string, tag: string, body: string): Shape | null {
  const pts = points(body)
  const first = pts[0] ?? [0, 0]
  switch (element) {
    case 'filled-circle':
      return { disc: [...first, num(tag, 'radius')] }
    case 'circle':
      return { circle: [...first, num(tag, 'radius')], width: num(tag, 'thickness') }
    case 'lines':
      return { line: polyline(pts, false), width: num(tag, 'thickness'), cap: cap(tag), join: join(tag) }
    case 'polygon':
      return { line: polyline(pts, true), width: num(tag, 'thickness'), cap: join(tag) === 'round' ? 'round' : 'butt', join: join(tag) }
    case 'beziers':
      return { line: beziers(pts, false), width: num(tag, 'thickness'), cap: cap(tag), join: 'round' }
    case 'filled-polygon':
      return { area: polyline(pts, true) }
    case 'filled-beziers':
      return { area: beziers(pts, true) }
    default:
      return null // name, text
  }
}

const raw = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(SOURCE_URL)).text()
const xml = raw.replace(/<!--[\s\S]*?-->/g, '') // the header comment documents the format with example tags
const symbols: string[] = []
for (const m of xml.matchAll(/<symbol\b([^>]*)>([\s\S]*?)<\/symbol>/g)) {
  const [, attrs = '', body = ''] = m
  const standard = attr(attrs, 'standard')
  if (standard === '2004') continue // replaced in the 2018 standard; 2024 builds on 2018
  const id = attr(attrs, 'id')
  const column = attr(attrs, 'kind')
  const name = body.match(/<name lang="en">([^<]*)<\/name>/)?.[1]
  if (!id || !column || !name) throw new Error(`incomplete symbol: ${attrs}`)
  const shapes: Shape[] = []
  for (const s of body.matchAll(/<([a-z-]+)\b([^>]*?)(?:\/>|>([\s\S]*?)<\/\1>)/g)) {
    const made = shape(s[1] ?? '', s[2] ?? '', s[3] ?? '')
    if (made) shapes.push(made)
  }
  const entry = {
    id,
    column,
    name: name.replace(/&amp;/g, '&'),
    ...(attr(attrs, 'size-is-depth') === 'true' ? { sizeIsDepth: true } : {}),
    shapes,
  }
  symbols.push(`  ${JSON.stringify(entry)},`)
}

writeFileSync(
  OUT,
  `// Generated by scripts/import-description-symbols.ts from Purple Pen's symbols.xml
// (github.com/petergolde/PurplePen, commit ${COMMIT}). Do not edit by hand.
//
// Copyright (c) 2006-2008, Peter Golde. All rights reserved. Used under the BSD 3-clause licence; the full
// licence text is in THIRD-PARTY-NOTICES.md.
//
// Coordinates: a symbol fills a box from (-100, -100) to (100, 100), y up; instruction lines (columns
// V-Z) are 1600 units wide.
import type { DescriptionSymbolDef } from './symbols.ts'

export const SYMBOLS: DescriptionSymbolDef[] = [
${symbols.join('\n')}
]
`,
)
console.log(`${symbols.length} symbols written to ${OUT.pathname}`)
